/** United States, Japan, then everyone else A to Z. */
export const COUNTRIES: Country[] = [...PINNED, ...OTHERS.sort((a, b) => a.name.localeCompare(b.name))];

const CODES = new Set(COUNTRIES.map((country) => country.code));

export const isCountryCode = (value: unknown): value is string =>
  typeof value === "string" && CODES.has(value);

export const countryName = (code: string): string =>
  COUNTRIES.find((country) => country.code === code)?.name ?? code;
